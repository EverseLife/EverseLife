/**
 * Где напечататься впервые (D-013, D-182).
 *
 * Первое решение новичка, и оно намеренно про людей, а не про числа: цены и
 * срока здесь нет вовсе — **первое тело печатается сразу и бесплатно** у любой
 * двери (D-040). Двенадцать часов Принтера Предтеч начинают действовать со
 * второй печати, и говорить о них на этом экране значило бы врать.
 *
 * Карточки стоят рядом, чтобы за десять секунд стало видно главное устройство
 * мира: города разные, условия назначают они сами, и никто не обязан быть
 * добрым. Принтер Предтеч — последней карточкой: запасная дверь, у которой нет
 * ни жителей, ни казны, и она открыта всегда.
 *
 * Условия печати (D-184) стоят строками таблицы, а не в тексте: их движок
 * исполняет, и человек обязан видеть их до нажатия, а не узнавать из отказа.
 */

import { useMemo, useState } from "react";
import * as api from "../api";
import type { Door } from "../api";

type Props = {
  двери: Door[];
  имя: string;
  busy: boolean;
  trouble?: string | null;
  onPick: (node: string) => void;
  onBack: () => void;
};

export function Doors({ двери, имя, busy, trouble, onPick, onBack }: Props) {
  //: Список приходит уже отсортированным — людные города впереди (D-187), —
  //: а поиск сужает его по имени города или узла. Пустой поиск — весь список.
  const [query, setQuery] = useState("");
  const видимые = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return двери;
    return двери.filter(
      (д) =>
        д.name.toLowerCase().includes(q) ||
        (д.city ?? "").toLowerCase().includes(q) ||
        (д.precursor && "предтеч".includes(q)),
    );
  }, [двери, query]);

  return (
    <section className="wide doors-step">
      <h1>Где вас напечатать</h1>
      <p className="note center">
        {имя}, тела у вас ещё нет — есть выбор машины, которая его соберёт.
        Первое тело печатается сразу и бесплатно везде; дальше за скорость
        платят (D-040).
      </p>

      <div className="row search">
        <input
          type="search"
          placeholder="найти город"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          aria-label="поиск города"
        />
        <span className="note">
          {видимые.length} из {двери.length} · сортировка по людям в городе
        </span>
      </div>

      {двери.length === 0 ? (
        <p className="trouble">
          В мире нет ни одного биопринтера. Этого положения быть не должно: вход
          в игру не блокируется никогда (D-028).
        </p>
      ) : видимые.length === 0 ? (
        <p className="note center">Ничего не нашлось — попробуйте иначе.</p>
      ) : (
        <div className="doors">
          {видимые.map((дверь) => (
            <section key={дверь.node}>
              {/* В заголовке — чем эта дверь отличается от соседней. Город
                  вынесен в строку: у столицы дверей две, и одинаковые
                  заголовки не давали бы их различить. */}
              <h2>{дверь.precursor ? "Принтер Предтеч" : дверь.name}</h2>
              <p className="note">
                {дверь.precursor
                  ? "Вечная машина настоящих людей: ничьей казны не требует и не откажет никому."
                  : "Городской биопринтер: работает на энергии и железе города."}
              </p>
              <table>
                <tbody>
                  <tr>
                    <td>город</td>
                    <td className="num">{дверь.city ?? "вне города"}</td>
                  </tr>
                  <tr>
                    <td>людей сейчас</td>
                    <td className="num">{дверь.city ? дверь.population : "—"}</td>
                  </tr>
                  <tr>
                    <td>граждан</td>
                    <td className="num">{дверь.city ? дверь.citizens : "—"}</td>
                  </tr>
                  <tr>
                    <td>подъёмные</td>
                    <td className="num">
                      {дверь.grant > 0 ? `${api.tk(дверь.grant)} ₭` : "нет"}
                    </td>
                  </tr>
                  <tr>
                    <td>первое тело</td>
                    <td className="num">сразу</td>
                  </tr>
                  {/* Условия печати (D-184). Показаны у городских дверей и
                      только у них: у Предтеч условий нет и быть не может —
                      машина ничья. */}
                  {дверь.city && (
                    <>
                      <tr>
                        <td>гражданство</td>
                        <td className="num">
                          {дверь.citizenship ? обязательство(дверь.term) : "не требуется"}
                        </td>
                      </tr>
                      <tr>
                        <td>налог с продажи</td>
                        <td className="num">
                          {дверь.tax > 0 ? `${дверь.tax}%` : "нет"}
                        </td>
                      </tr>
                    </>
                  )}
                </tbody>
              </table>
              {/* Слово города: его пишет власть, а не движок (D-183). Молчащий
                  город показывает только числа — сочинять за него нечего. */}
              {дверь.about && <p className="say">«{дверь.about}»</p>}
              <div className="row">
                <button onClick={() => onPick(дверь.node)} disabled={busy}>
                  Печататься здесь
                </button>
              </div>
            </section>
          ))}
        </div>
      )}

      <p className="note">
        Подъёмные платит город из своей казны, а не мир из воздуха (D-153):
        новый житель городу выгоден, и потому за него торгуются.
      </p>
      <p className="note">
        Строки таблицы движок исполняет: обязательное гражданство наступает в
        момент печати и держит весь срок, налог удерживается с каждой продажи
        (D-184). У Принтера Предтеч условий нет — машина ничья.
      </p>
      <p className="note">
        В кавычках — слово самого города. Это обещание живых людей, и движок за
        него не отвечает: не сдержали — дело суда (D-183).
      </p>
      {trouble && <p className="trouble">{trouble}</p>}
      <div className="row">
        <button className="quiet" onClick={onBack} disabled={busy}>
          ← назад
        </button>
      </div>
    </section>
  );
}

/** Обязательство словами: «на 3 суток» либо просто «обязательно». */
function обязательство(суток: number): string {
  if (суток <= 0) return "обязательно";
  if (суток < 1) return `обязательно · ${Math.round(суток * 24)} ч`;
  return `обязательно · ${суток % 1 === 0 ? суток : суток.toFixed(1)} сут`;
}
